-- MUSIC VIDEO AWARDS — initial database schema
-- Run this whole file in a NEW Supabase project's SQL Editor.
-- All audience votes require a single-use printed/distributed code.
-- RLS is enabled on every public table. The only public mutation is cast_vote RPC.

create schema if not exists private;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.teams (
  id text primary key,
  name text not null,
  display_order integer not null unique
);
create table if not exists public.criteria (
  id integer generated by default as identity primary key,
  name text not null,
  max_points integer not null check (max_points between 1 and 100),
  display_order integer not null unique
);
create table if not exists public.event_settings (
  id integer primary key check (id=1),
  event_title text not null default 'Music Video Awards',
  expected_judges integer check (expected_judges between 1 and 50),
  scoring_open boolean not null default true,
  voting_open boolean not null default true,
  results_released boolean not null default false
);
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null check (role in ('admin','judge')),
  active boolean not null default true
);
create table if not exists public.scores (
  judge_id uuid not null references public.profiles(id) on delete cascade,
  team_id text not null references public.teams(id),
  criterion_id integer not null references public.criteria(id),
  points integer not null check (points >= 0),
  updated_at timestamptz not null default now(),
  primary key(judge_id,team_id,criterion_id)
);
create table if not exists public.voter_codes (
  id bigint generated always as identity primary key,
  code_hash text not null unique,
  used_at timestamptz
);
create table if not exists public.votes (
  id bigint generated always as identity primary key,
  code_id bigint not null unique references public.voter_codes(id),
  team_id text not null references public.teams(id),
  cast_at timestamptz not null default now()
);
create index if not exists idx_scores_judge_id on public.scores(judge_id);
create index if not exists idx_votes_team_id on public.votes(team_id);

