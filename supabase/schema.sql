create policy "Read published teams" on public.teams for select to anon,authenticated using(true);
create policy "Read rubric" on public.criteria for select to anon,authenticated using(true);
create policy "Read event status" on public.event_settings for select to anon,authenticated using(true);
create policy "Admin settings edits" on public.event_settings for update to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "Admin rubric edits before any scoring" on public.criteria for update to authenticated
  using ((select private.is_admin()) and not exists(select 1 from public.scores))
  with check ((select private.is_admin()) and not exists(select 1 from public.scores));
create policy "Admin or own profile" on public.profiles for select to authenticated
  using (id=(select auth.uid()) or (select private.is_admin()));
create policy "Admin or own scores" on public.scores for select to authenticated
  using ((select private.is_admin()) or (judge_id=(select auth.uid()) and (select private.is_judge())));
create policy "Judge scores own work" on public.scores for insert to authenticated
  with check (judge_id=(select auth.uid()) and (select private.is_judge()));
create policy "Judge edits own scores" on public.scores for update to authenticated
  using (judge_id=(select auth.uid()) and (select private.is_judge()))
  with check (judge_id=(select auth.uid()) and (select private.is_judge()));
create policy "Admin reads code status" on public.voter_codes for select to authenticated
  using ((select private.is_admin()));
create policy "Admin reads votes" on public.votes for select to authenticated
  using ((select private.is_admin()));

-- Always revalidate numeric limits and current scoring state on the server.
create or replace function private.validate_score() returns trigger
language plpgsql set search_path = '' as $$
declare v_max integer; v_open boolean;
begin
  if tg_op = 'UPDATE' and (
    new.judge_id is distinct from old.judge_id or
    new.team_id is distinct from old.team_id or
    new.criterion_id is distinct from old.criterion_id
  ) then raise exception 'Score identity cannot be changed.'; end if;
  select scoring_open into v_open from public.event_settings where id=1;
  if v_open is distinct from true then raise exception 'Judging is closed.'; end if;
  select max_points into v_max from public.criteria where id=new.criterion_id;
  if v_max is null or new.points<0 or new.points>v_max then raise exception 'Invalid criterion score.'; end if;
  if not exists(select 1 from public.profiles where id=new.judge_id and role='judge' and active=true)
     then raise exception 'Active judge account required.'; end if;
  new.updated_at=now();
  return new;
end;$$;
create trigger validate_judge_score before insert or update on public.scores
for each row execute function private.validate_score();

-- The hashes below are SHA-256 digests of codes. Plaintext voting codes are
-- returned only once to the administrator's browser to download as a CSV.
create or replace function private.issue_voter_codes_internal(p_codes text[]) returns integer
language plpgsql security definer set search_path = '' as $$
declare v_code text; v_count integer;
begin
  if not private.is_admin() then raise exception 'Administrator only.'; end if;
  v_count=coalesce(array_length(p_codes,1),0);
  if v_count<1 or v_count>500 then raise exception 'Issue 1–500 codes at a time.'; end if;
  foreach v_code in array p_codes loop
    if v_code !~ '^MVA-[A-HJ-NP-Z2-9]{12}$' then raise exception 'Invalid voting-code format.'; end if;
    insert into public.voter_codes(code_hash)
    values (pg_catalog.encode(extensions.digest(pg_catalog.convert_to(v_code,'UTF8'),'sha256'),'hex'));
  end loop;
  return v_count;
end;$$;

-- Take a row lock for the code so two simultaneous requests cannot reuse it.
create or replace function private.cast_vote_internal(p_code text,p_team_id text) returns text
language plpgsql security definer set search_path = '' as $$
declare v_code_id bigint; v_used timestamptz; v_open boolean; v_digest text;
begin
  select voting_open into v_open from public.event_settings where id=1 for share;
  if v_open is distinct from true then raise exception 'Audience voting is closed.'; end if;
  if p_team_id is null or not exists(select 1 from public.teams where id=p_team_id) then
    raise exception 'Invalid group.';
  end if;
  if p_code is null or pg_catalog.length(p_code)>60 then raise exception 'Invalid voting code.'; end if;
  v_digest=pg_catalog.encode(extensions.digest(pg_catalog.convert_to(pg_catalog.upper(pg_catalog.btrim(p_code)),'UTF8'),'sha256'),'hex');
  select id,used_at into v_code_id,v_used from public.voter_codes where code_hash=v_digest for update;
  if v_code_id is null or v_used is not null then raise exception 'Invalid or already-used voting code.'; end if;
  insert into public.votes(code_id,team_id) values(v_code_id,p_team_id);
  update public.voter_codes set used_at=now() where id=v_code_id;
  return 'Vote accepted!';
end;$$;

-- Invoker wrappers are the only functions exposed to the API.
create or replace function public.issue_voter_codes(p_codes text[]) returns integer
language sql security invoker set search_path = '' as $$
  select private.issue_voter_codes_internal(p_codes);
$$;
create or replace function public.cast_vote(p_code text,p_team_id text) returns text
language sql security invoker set search_path = '' as $$
  select private.cast_vote_internal(p_code,p_team_id);
$$;

